const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const data = require('emojibase-data/en/data.json');
const emojibaseShortcodes = require('emojibase-data/en/shortcodes/emojibase.json');
const joypixelsShortcodes = require('emojibase-data/en/shortcodes/joypixels.json');
const pinnedShortnames = require('./pinned-shortnames');
// Hand-maintained, and the same file `legacyShortnames.ts` re-exports. See docs/emojis.md.
const legacyShortnames = require('../app/lib/constants/emojis/legacyShortnames.json');

const OUTPUT = path.join(__dirname, '..', 'app', 'lib', 'constants', 'emojis', 'data.ts');

// Same mapping the web client uses, so both clients agree on which tab an emoji lands in.
// Group 2 (component: skin tones, hair styles) has no picker category and is skipped.
const groupToCategory = {
	0: 'people', // smileys & emotion
	1: 'people', // people & body
	3: 'nature', // animals & nature
	4: 'food', // food & drink
	5: 'travel', // travel & places
	6: 'activity', // activities
	7: 'objects', // objects
	8: 'symbols', // symbols
	9: 'flags' // flags
};

const CATEGORIES = ['people', 'nature', 'food', 'activity', 'travel', 'objects', 'symbols', 'flags'];

// The variation selector is presentational, so `⚠️` and `⚠` are the same emoji here.
const bare = unicode => unicode.replace(/\uFE0F/g, '');

const isRegionalIndicator = hexcode => {
	if (hexcode.includes('-')) {
		return false;
	}
	const cp = parseInt(hexcode, 16);
	return cp >= 0x1f1e6 && cp <= 0x1f1ff;
};

const getShortcodes = hexcode => {
	const entry = joypixelsShortcodes[hexcode] ?? emojibaseShortcodes[hexcode];
	if (!entry) {
		return [];
	}
	return Array.isArray(entry) ? entry : [entry];
};

const build = () => {
	const emojisByCategory = Object.fromEntries(CATEGORIES.map(key => [key, []]));
	const shortnameToUnicode = {};
	const aliasesByName = {};

	// First write wins, and three things below depend on it: joypixels shortcodes are looked up
	// before emojibase ones, an emoji's first shortcode is added before its aliases, and the base
	// emoji is added before its tone variants. Whoever gets there first owns the name.
	const add = (shortname, unicode) => {
		const key = `:${shortname}:`;
		if (!(key in shortnameToUnicode)) {
			shortnameToUnicode[key] = unicode;
		}
	};

	data.forEach(emoji => {
		if (emoji.group === 2) {
			return;
		}

		const isRegional = isRegionalIndicator(emoji.hexcode);
		const category = groupToCategory[emoji.group] ?? (isRegional ? 'flags' : undefined);
		if (!category) {
			return;
		}

		const codes = getShortcodes(emoji.hexcode);
		if (codes.length === 0) {
			return;
		}

		const [name, ...aliases] = codes;

		add(name, emoji.emoji);
		aliases.forEach(alias => add(alias, emoji.emoji));
		if (aliases.length) {
			aliasesByName[name] = aliases;
		}

		// Regional indicators are the letter tiles that combine into flags, not emojis
		// the picker should list on their own.
		if (!emoji.tone && !isRegional) {
			emojisByCategory[category].push(name);
		}

		// The picker has no tone selector, so tone variants only need to resolve when a
		// message already contains one — they stay out of the categories and out of search.
		(emoji.skins ?? []).forEach(skin => {
			if (!skin.tone) {
				return;
			}
			const tones = Array.isArray(skin.tone) ? skin.tone : [skin.tone];
			getShortcodes(skin.hexcode).forEach(code => add(code, skin.emoji));
			add(`${name}_tone${tones.join('-')}`, skin.emoji);
		});
	});

	return { emojisByCategory, shortnameToUnicode, aliasesByName };
};

// Pins hold a shortname at the glyph a previous release resolved. Applied here, offline, because
// the generated map is read first at runtime — a hand-maintained map cannot override it.
const applyPins = shortnameToUnicode => {
	const applied = [];
	const stale = [];
	const gone = [];
	const displaced = [];

	Object.keys(pinnedShortnames).forEach(shortname => {
		const upstream = shortnameToUnicode[shortname];
		if (!upstream) {
			gone.push(shortname);
			return;
		}
		if (bare(upstream) === bare(pinnedShortnames[shortname])) {
			stale.push(shortname);
			return;
		}
		shortnameToUnicode[shortname] = pinnedShortnames[shortname];
		applied.push(shortname);
		displaced.push(upstream);
	});

	// A pin can take the last shortname an emoji had, leaving nothing that resolves to it.
	const resolvable = new Set(Object.keys(shortnameToUnicode).map(key => bare(shortnameToUnicode[key])));
	const orphaned = displaced.filter(unicode => !resolvable.has(bare(unicode)));

	return { applied, stale, gone, orphaned };
};

const header = filename =>
	`// Generated by scripts/generate-emoji-data.js — do not edit by hand.\n// Run \`pnpm generate-emoji-data\` after bumping the emojibase-data dependency.\n// See docs/emojis.md.\n/* eslint-disable */\n${filename}`;

const stringifyList = (name, list, indent = '\t') =>
	`${name}: [\n${list.map(item => `${indent}\t'${item}'`).join(',\n')}\n${indent}]`;

const writeData = ({ emojisByCategory, shortnameToUnicode, aliasesByName }) => {
	const categories = CATEGORIES.map(key => `\t${stringifyList(key, emojisByCategory[key])}`).join(',\n');

	const map = Object.keys(shortnameToUnicode)
		.map(key => `\t'${key}': '${shortnameToUnicode[key]}'`)
		.join(',\n');

	const aliases = Object.keys(aliasesByName)
		.map(name => `\t${stringifyList(`'${name}'`, aliasesByName[name])}`)
		.join(',\n');

	const contents = header(`
export const emojisByCategory = {
${categories}
};

// Every shortname the app can resolve, aliases and skin tone variants included.
// Values come from emojibase, except the ones held back by scripts/pinned-shortnames.js.
export const shortnameToUnicodeMap: { [key: string]: string } = {
${map}
};

// Alternate shortnames for an emoji, keyed by the name listed in \`emojisByCategory\`.
// The picker lists one name per emoji, so searching matches every alias but returns the listed name.
export const aliasesByEmojiName: { [key: string]: string[] } = {
${aliases}
};
`);

	fs.writeFileSync(OUTPUT, contents, 'utf8');

	// Format the output so a plain `pnpm format-lint` never rewrites it, which would make the
	// next run of this script look like a real diff.
	execFileSync('npx', ['oxfmt', OUTPUT], { stdio: 'ignore' });
};

// Legacy names stay searchable: they are folded into the alias list of whichever current
// name renders the same emoji. Done here, offline, so nothing reverse-maps at runtime.
const foldLegacyIntoAliases = ({ emojisByCategory, shortnameToUnicode, aliasesByName }, legacy) => {
	const nameByUnicode = {};
	CATEGORIES.forEach(category =>
		emojisByCategory[category].forEach(name => {
			const unicode = shortnameToUnicode[`:${name}:`];
			if (unicode && !(bare(unicode) in nameByUnicode)) {
				nameByUnicode[bare(unicode)] = name;
			}
		})
	);

	let folded = 0;
	Object.keys(legacy).forEach(shortname => {
		const name = nameByUnicode[bare(legacy[shortname])];
		const alias = shortname.slice(1, -1);
		if (!name || alias === name) {
			return;
		}
		if (!aliasesByName[name]) {
			aliasesByName[name] = [];
		}
		if (!aliasesByName[name].includes(alias)) {
			aliasesByName[name].push(alias);
			folded += 1;
		}
	});

	return folded;
};

const emojiData = build();
const pins = applyPins(emojiData.shortnameToUnicode);
const folded = foldLegacyIntoAliases(emojiData, legacyShortnames);

writeData(emojiData);

const total = CATEGORIES.reduce((acc, key) => acc + emojiData.emojisByCategory[key].length, 0);
console.log(`🚀 Emoji data generated: ${total} emojis, ${Object.keys(emojiData.shortnameToUnicode).length} shortnames.`);
console.log(`ℹ️  ${Object.keys(legacyShortnames).length} legacy shortnames read, ${folded} kept searchable as aliases.`);

console.log(`📌 ${pins.applied.length} shortnames pinned to the glyph a previous release resolved.`);

const stale = Object.keys(legacyShortnames).filter(key => key in emojiData.shortnameToUnicode);
if (stale.length) {
	console.log(
		`⚠️  ${stale.length} entries in legacyShortnames.json are back in emojibase and can be removed: ${stale.join(', ')}`
	);
}

if (pins.stale.length) {
	console.log(`⚠️  ${pins.stale.length} pins now match emojibase and can be removed: ${pins.stale.join(', ')}`);
}

if (pins.gone.length) {
	console.log(
		`⚠️  ${pins.gone.length} pins no longer resolve — emojibase dropped the name, so it belongs in legacyShortnames.json: ${pins.gone.join(', ')}`
	);
}

if (pins.orphaned.length) {
	console.log(`⚠️  a pin took the last shortname of ${pins.orphaned.join(' ')} — nothing resolves to it any more.`);
}
